"""Live view via go2rtc.

go2rtc keeps one connection per camera stream and re-publishes it for
browsers (MSE / WebRTC / HLS) and for our recorder (RTSP). Its API is never
exposed directly: the NVR generates its config and proxies only the player
endpoints after checking the user's login.
"""
from __future__ import annotations

import asyncio
import logging
from pathlib import Path

import httpx
import websockets
import yaml

from .config import Config

log = logging.getLogger("nvr.live")


def stream_names(cfg: Config) -> set[str]:
    names = set()
    for c in cfg.cameras:
        if c.enabled:
            names.add(c.id)
            names.add(c.id + "_sub")
    return names


def go2rtc_config(cfg: Config) -> dict:
    streams = {}
    for c in cfg.cameras:
        if not c.enabled:
            continue
        main = [c.main_rtsp]
        if c.audio:
            # Browsers need AAC (MSE) / Opus (WebRTC); transcoded only on demand.
            main.append(f"ffmpeg:{c.id}#audio=aac")
            if cfg.webrtc:
                main.append(f"ffmpeg:{c.id}#audio=opus")
        streams[c.id] = main
        streams[c.id + "_sub"] = [c.sub_rtsp]
    conf = {
        "log": {"level": "info"},
        "api": {"listen": ":1984"},
        "rtsp": {"listen": ":8554"},
        "streams": streams,
    }
    if cfg.webrtc:
        conf["webrtc"] = {"listen": ":8555", "candidates": cfg.webrtc_candidates or []}
    else:
        conf["webrtc"] = {"listen": ""}
    return conf


async def sync_go2rtc(cfg: Config) -> None:
    """Write go2rtc.yaml if it changed and ask go2rtc to reload it."""
    if not cfg.go2rtc_config:
        return
    path: Path = cfg.go2rtc_config
    text = "# Generated by FarNVR from config.yaml - do not edit\n" + yaml.safe_dump(
        go2rtc_config(cfg), sort_keys=False, allow_unicode=True)
    old = path.read_text() if path.exists() else ""
    if old == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(text)
    tmp.chmod(0o600)
    tmp.replace(path)
    log.info("go2rtc config updated, restarting go2rtc")
    for _ in range(30):
        try:
            async with httpx.AsyncClient(timeout=5) as client:
                await client.post(f"{cfg.go2rtc_api}/api/restart")
            return
        except httpx.HTTPError:
            await asyncio.sleep(2)


async def proxy_websocket(client_ws, upstream_url: str) -> None:
    """Pump frames between the browser and go2rtc until one side closes."""
    try:
        async with websockets.connect(upstream_url, max_size=None, open_timeout=10) as upstream:
            async def to_upstream():
                while True:
                    msg = await client_ws.receive()
                    if msg["type"] == "websocket.disconnect":
                        break
                    if msg.get("text") is not None:
                        await upstream.send(msg["text"])
                    elif msg.get("bytes") is not None:
                        await upstream.send(msg["bytes"])

            async def to_client():
                async for data in upstream:
                    if isinstance(data, bytes):
                        await client_ws.send_bytes(data)
                    else:
                        await client_ws.send_text(data)

            tasks = [asyncio.create_task(to_upstream()), asyncio.create_task(to_client())]
            done, pending = await asyncio.wait(tasks, return_when=asyncio.FIRST_COMPLETED)
            for t in pending:
                t.cancel()
            await asyncio.gather(*pending, return_exceptions=True)
    except (OSError, websockets.WebSocketException, asyncio.TimeoutError) as exc:
        log.debug("live proxy closed: %s", exc)
    finally:
        try:
            await client_ws.close()
        except RuntimeError:
            pass
